  "e-Way Bill No. : 531999351397 Mode : 1 - Road Generated Date : 5-May-26 3:17 PM",
  "Generated By : 32ABCDE1234F1Z5 Approx Distance : 45 KM Valid Upto : 6-May-26 11:59 PM",
