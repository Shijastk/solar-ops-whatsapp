describe("document parser", () => {
  it("extracts operational fields without relying on exact coordinates", () => {
    const parsed = parseOperationalDocumentText(deliveryNote);

    expect(parsed.parseStatus).toBe("ready_for_review");
    expect(parsed.supplierName).toBe("SUN GRID SOLUTIONS LIMITED");
    expect(parsed.supplierGstin).toBe("32ABCDE1234F1Z5");
    expect(parsed.documentNumber).toBe("SG000123");
    expect(parsed.documentDate).toBe("2026-05-05");
    expect(parsed.ewayBillNumber).toBe("531999351397");
    expect(parsed.consigneeName).toBe("CUSTOMER ONE");
    expect(parsed.consigneePincode).toBe("673600");
    expect(parsed.vehicleNumber).toBe("KL11AA1234");
    expect(parsed.approximateDistanceKm).toBe(45);
    expect(parsed.supplyType).toBe("Outward-Job Work");
    expect(parsed.transactionType).toBe("Bill From - Dispatch From");
    expect(parsed.taxableAmount).toBe(164378.7);
    expect(parsed.totalAmount).toBe(176026.86);
    expect(parsed.items).toHaveLength(3);
    expect(parsed.items[0]).toMatchObject({
      description: "Solar 560 Wp Topcon Panel",
      hsnSac: "8541",
      quantity: 6,
      unit: "NOS",
      rate: 20000,
      amount: 120000,
    });
  });

  it("does not invent a phone number from unrelated document digits", () => {
    const parsed = parseOperationalDocumentText(deliveryNote);
    expect(parsed.consigneePhone).toBeNull();
    expect(parsed.buyerPhone).toBeNull();
  });

  it("marks PDFs without a usable text layer for OCR instead of inventing data", () => {
    const parsed = parseOperationalDocumentText("PDF image only");
    expect(parsed.parseStatus).toBe("needs_ocr");
    expect(parsed.missingFields).toEqual(["text_layer"]);
    expect(parsed.items).toEqual([]);
  });

  it("normalizes dates and product descriptions", () => {
    expect(parseDocumentDate("5-May-26")).toBe("2026-05-05");
    expect(parseDocumentDate("05/05/2026")).toBe("2026-05-05");
    expect(normalizeProductDescription(" Solar  560-Wp / TOPCON ")).toBe(
      "solar 560 wp topcon",
    );
  });
});
